import { fileURLToPath } from "node:url";
import { Language, Parser, type Node } from "web-tree-sitter";
import { lexSql, lexYaml, type RawComment } from "./lexers";

export type Lang = "typescript" | "tsx" | "c_sharp" | "dart" | "bash" | "yaml" | "sql";

export type Allow = { rules: string[]; reason: string; line: number };

export type Comment = {
  line: number;
  endLine: number;
  column: number;
  text: string;
  body: string;
  doc: boolean;
  trailing: boolean;
  directive: boolean;
  allows: Allow[];
  next: string;
};

const extensions: Record<string, Lang> = {
  ts: "typescript",
  mts: "typescript",
  cts: "typescript",
  tsx: "tsx",
  js: "tsx",
  jsx: "tsx",
  mjs: "tsx",
  cjs: "tsx",
  cs: "c_sharp",
  dart: "dart",
  sh: "bash",
  bash: "bash",
  yml: "yaml",
  yaml: "yaml",
  sql: "sql",
};

export function languageOf(path: string): Lang | null {
  const ext = /\.([^./\\]+)$/.exec(path)?.[1]?.toLowerCase();
  return ext ? (extensions[ext] ?? null) : null;
}

const directive =
  /^(eslint[- ]|@ts-|prettier-ignore|biome-ignore|deno-lint|ignore(_for_file)?:|ReSharper\s|resharper_|#pragma|nolint|noqa|shellcheck\s|istanbul\s|c8\s|v8\s|jscpd:|type:\s*ignore|pyright:|<reference\s|<auto-generated|yaml-language-server:|syntax=|cspell:|coverage:ignore|dart format)/i;

const allowLine = /^silence-allow\s+([\w-]+(?:\s*,\s*[\w-]+)*)\s*(?::\s*(.*))?$/;

let ready: Promise<void> | undefined;
const languages = new Map<Lang, Promise<Language>>();

async function parserFor(lang: Lang): Promise<Parser> {
  ready ??= Parser.init();
  await ready;
  if (!languages.has(lang)) {
    const wasm = fileURLToPath(new URL(`../grammars/tree-sitter-${lang}.wasm`, import.meta.url));
    languages.set(lang, Language.load(wasm));
  }
  const parser = new Parser();
  parser.setLanguage(await languages.get(lang)!);
  return parser;
}

async function rawComments(lang: Lang, source: string): Promise<RawComment[]> {
  if (lang === "sql") return lexSql(source);
  if (lang === "yaml") return lexYaml(source);
  const tree = (await parserFor(lang)).parse(source);
  if (!tree) return [];
  const out: RawComment[] = [];
  const walk = (node: Node) => {
    if (node.type.includes("comment")) {
      out.push({ line: node.startPosition.row + 1, endLine: node.endPosition.row + 1, column: node.startPosition.column + 1, text: node.text });
      return;
    }
    for (const child of node.children) if (child) walk(child);
  };
  walk(tree.rootNode);
  tree.delete();
  return out;
}

function stripMarkers(text: string): string[] {
  if (text.startsWith("/*")) {
    return text
      .replace(/^\/\*+!?/, "")
      .replace(/\*+\/$/, "")
      .split("\n")
      .map((l) => l.replace(/^\s*\*(?!\*)\s?/, "").trim());
  }
  return text.split("\n").map((l) => l.trim().replace(/^(\/\/[\/!]?|#+|--)\s?/, "").trim());
}

const isDoc = (text: string) => /^\/\/\/(?!\/)/.test(text) || /^\/\*\*(?!\/)/.test(text);

export async function extractComments(path: string, source: string): Promise<Comment[] | null> {
  const lang = languageOf(path);
  if (!lang) return null;
  const lines = source.split("\n");
  const raws = (await rawComments(lang, source)).sort((a, b) => a.line - b.line || a.column - b.column);
  const covered = new Set<number>();

  const singles = raws.map((raw) => {
    const prefix = lines[raw.line - 1]!.slice(0, raw.column - 1);
    const trailing = prefix.trim() !== "";
    if (!trailing) for (let l = raw.line; l <= raw.endLine; l++) covered.add(l);
    const bodyLines = stripMarkers(raw.text);
    const allow = bodyLines.length === 1 ? allowLine.exec(bodyLines[0]!) : null;
    return {
      raw,
      trailing,
      prefix,
      kind: raw.text.startsWith("/*") ? "block" : "line",
      doc: isDoc(raw.text),
      allow: allow ? { rules: allow[1]!.split(/\s*,\s*/), reason: (allow[2] ?? "").trim(), line: raw.line } : null,
      body: bodyLines,
      directive: raw.text.startsWith("#!") || directive.test(bodyLines.find((l) => l) ?? ""),
    };
  });

  const comments: (Comment & { mergeable: boolean })[] = [];
  let current: (Comment & { mergeable: boolean }) | null = null;
  for (const s of singles) {
    const mergeable = s.kind === "line" && !s.trailing && !s.directive;
    const joins =
      current && current.mergeable && mergeable && s.raw.line === current.endLine + 1 && (current.doc === s.doc || current.body === "");
    if (joins && current) {
      current.endLine = s.raw.endLine;
      current.text += "\n" + lines[s.raw.line - 1]!.trim();
      current.doc ||= s.doc;
      if (s.allow) current.allows.push(s.allow);
      else current.body = [current.body, ...s.body].filter((l) => l !== "").join("\n");
      continue;
    }
    current = {
      line: s.raw.line,
      endLine: s.raw.endLine,
      column: s.raw.column,
      text: s.raw.text,
      body: s.allow ? "" : s.body.join("\n").trim(),
      doc: s.doc,
      trailing: s.trailing,
      directive: s.directive && !s.allow,
      allows: s.allow ? [s.allow] : [],
      next: s.trailing ? s.prefix.trim() : "",
      mergeable: mergeable || s.allow !== null,
    };
    comments.push(current);
  }

  return comments.map(({ mergeable: _, ...c }) => {
    if (c.trailing) return c;
    for (let l = c.endLine + 1; l <= lines.length; l++) {
      const text = lines[l - 1]!.trim();
      if (text !== "" && !covered.has(l)) return { ...c, next: text };
    }
    return c;
  });
}
